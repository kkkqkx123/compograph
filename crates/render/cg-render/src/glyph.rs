/// Bit rows of the glyph for `byte`, or blank rows outside printable ASCII.
pub fn glyph_rows(byte: u8) -> [u8; GLYPH_HEIGHT] {
    if (32..=126).contains(&byte) {
        GLYPHS[(byte - 32) as usize]
    } else {
        [0; GLYPH_HEIGHT]
    }
}

/// True for bytes with a real glyph in the table.
pub fn is_printable_ascii(byte: u8) -> bool {
    (32..=126).contains(&byte)
}

/// True when the glyph carries at least one set pixel.
pub fn glyph_is_empty(byte: u8) -> bool {
    glyph_rows(byte).iter().all(|row| *row == 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn printable_glyphs_cover_alphanumerics() {
        assert!(!glyph_is_empty(b'A'));
        assert!(!glyph_is_empty(b'0'));
        assert!(glyph_is_empty(b' '));
        assert!(glyph_rows(0xE4).iter().all(|row| *row == 0));
        assert!(is_printable_ascii(b'~'));
        assert!(!is_printable_ascii(0x7F));
        assert_eq!(GLYPHS.len(), 95);
        assert_eq!(GLYPH_ADVANCE, GLYPH_WIDTH + 1);
    }
}
